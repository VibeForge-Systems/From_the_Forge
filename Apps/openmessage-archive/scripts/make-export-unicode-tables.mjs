// Writes crates/oma-export/src/unicode_tables.rs (M6 slice 6d): the two
// Unicode property tables the export's hidden-character classifier needs,
// taken from this Node's own regular-expression engine, so the Rust
// classifier and "Copy text without invisible characters"
// (src/services/copyText.ts, D121) read the same properties:
//
// - JOINABLE: the class a zero-width joiner or non-joiner must sit
//   between to be kept, exactly copyText.ts's
//   /[\p{L}\p{M}\p{Extended_Pictographic}\p{Emoji_Modifier}]/u;
// - MARK: \p{M} (General_Category Mark), for the combining-run limit.
//
// No Unicode data file is downloaded or copied: the ranges are computed by
// testing every code point against the engine's properties. Run from the
// app directory:
//
//   node scripts/make-export-unicode-tables.mjs
//
// and commit the result. The Unicode version is written into the file.
import { writeFileSync } from 'node:fs';

const OUT = 'crates/oma-export/src/unicode_tables.rs';

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp += 1) {
    const inSet = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (inSet && start < 0) start = cp;
    if (!inSet && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

function table(name, doc, rs) {
  const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
  const lines = rs.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`);
  return `${doc}\npub(crate) const ${name}: &[(u32, u32)] = &[\n${lines.join('\n')}\n];\n`;
}

const joinable = ranges(/^[\p{L}\p{M}\p{Extended_Pictographic}\p{Emoji_Modifier}]$/u);
const mark = ranges(/^\p{M}$/u);

const text = `// @generated by scripts/make-export-unicode-tables.mjs; do not edit.
// Unicode ${process.versions.unicode} (Node ${process.versions.node}, ICU ${process.versions.icu}).
//! Unicode property tables for \`hidden.rs\`, as sorted, disjoint,
//! inclusive code-point ranges.

${table(
  'JOINABLE',
  '/// `[\\p{L}\\p{M}\\p{Extended_Pictographic}\\p{Emoji_Modifier}]`: what a ZWJ or\n/// ZWNJ must sit between (with both neighbours non-ASCII) to be kept.',
  joinable,
)}
${table('MARK', '/// `\\p{M}`: combining marks (General_Category Mn, Mc, Me).', mark)}`;

writeFileSync(OUT, text);
console.log(`wrote ${OUT}: ${joinable.length} joinable ranges, ${mark.length} mark ranges`);
